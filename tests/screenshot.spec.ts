test('mystery modal has no horizontal document overflow on mobile', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start The Screenshot interactive mystery' }).click()
  const bounds = await page.getByRole('dialog').boundingBox()
  const viewport = page.viewportSize()
  expect(bounds).not.toBeNull()
  expect(viewport).not.toBeNull()
  if (bounds && viewport && viewport.width < 700) {
    expect(Math.abs(bounds.width - viewport.width)).toBeLessThanOrEqual(2)
    expect(Math.abs(bounds.height - viewport.height)).toBeLessThanOrEqual(3)
  }
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
  expect(overflow).toBeLessThanOrEqual(3)
})
