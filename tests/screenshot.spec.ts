import { expect, test } from '@playwright/test'

test('branching screenshot rumor can be investigated, corrected and awarded XP once', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Start The Screenshot interactive mystery' }).click()
  const dialog = page.getByRole('dialog', { name: /One screenshot/ })
  await expect(dialog.getByText('Fictional fundraiser, figures and messages.')).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'See what happens' })).toBeDisabled()
  await dialog.getByRole('button', { name: /Share it with the group/ }).click()
  await dialog.getByRole('button', { name: 'See what happens' }).click()
  await expect(dialog.getByRole('heading', { name: 'The accusation spreads.' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Open the evidence board' }).click()
  await expect(dialog.getByRole('button', { name: 'Take a second look' })).toBeDisabled()
  const first = dialog.getByRole('button', { name: /The conversation above it/ })
  await first.click()
  await expect(dialog.getByText(/Please fix the placeholder figure/)).toBeVisible()
  await first.click()
  await expect(dialog.getByText(/Please fix the placeholder figure/)).toHaveCount(0)
  await dialog.getByRole('button', { name: /What the screenshot left out/ }).click()
  await expect(dialog.getByRole('button', { name: 'Take a second look' })).toBeEnabled()
  await dialog.getByRole('button', { name: 'Take a second look' }).click()
  await expect(dialog.getByRole('heading', { name: /Real message/ })).toBeVisible()
  await dialog.getByRole('button', { name: /Ask for a clear public correction/ }).click()
  await dialog.getByRole('button', { name: 'See the ending' }).click()
  await expect(dialog.getByRole('heading', { name: 'You challenge the claim, not the person.' })).toBeVisible()
  await expect(dialog.getByText('+120 discovery XP · New experience')).toBeVisible()
  await dialog.getByRole('button', { name: 'Back to the Lab' }).click()
  await expect(page.locator('#my-progress').getByText('120 XP', { exact: true })).toBeVisible()
  await expect(page.locator('#my-progress').getByText('1 / 8 unique')).toBeVisible()
  await page.reload()
  await expect(page.locator('#my-progress').getByText('120 XP', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Start The Screenshot interactive mystery' }).click()
  await dialog.getByRole('button', { name: /Save it and check the source/ }).click()
  await dialog.getByRole('button', { name: 'See what happens' }).click()
  await expect(dialog.getByRole('heading', { name: 'One missing detail stands out.' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Open the evidence board' }).click()
  await dialog.getByRole('button', { name: /Full chat/ }).count().catch(() => 0)
  await dialog.getByRole('button', { name: /The conversation above it/ }).click()
  await dialog.getByRole('button', { name: /What viewers actually saw/ }).click()
  await dialog.getByRole('button', { name: 'Take a second look' }).click()
  await dialog.getByRole('button', { name: /Post the screenshot with a fraud accusation/ }).click()
  await dialog.getByRole('button', { name: 'See the ending' }).click()
  await expect(dialog.getByRole('heading', { name: 'The rumor outgrows the evidence.' })).toBeVisible()
  await expect(dialog.getByText('Previously explored · No repeat XP')).toBeVisible()
})

